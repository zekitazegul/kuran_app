String normalizeSurahName(String value) {
  var result = value.replaceAll('İ', 'i').replaceAll('I', 'ı').toLowerCase();
  const replacements = {'â': 'a', 'ā': 'a', 'î': 'i', 'û': 'u', 'ı': 'i',
    'ş': 's', 'ç': 'c', 'ğ': 'g', 'ö': 'o', 'ü': 'u', '‘': '', '’': ''};
  replacements.forEach((from, to) => result = result.replaceAll(from, to));
  return result;
}
